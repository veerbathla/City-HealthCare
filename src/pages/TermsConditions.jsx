/* ----------------------------------------------------------------------------
   Minimal markdown -> JSX renderer.
   Handles: # ## ### headings, * bullet lists, 1. numbered lists,
   > blockquotes, **bold**, [text](url) links, --- rules, blank-line paragraphs.
   Strips ONLY the markdown symbols; every word of the source text is kept.
---------------------------------------------------------------------------- */
function parseInline(str, keyBase) {
  const tokens = str.split(/(\*\*[^*]+?\*\*|\[[^\]]+\]\([^)]+\))/g);
  return tokens
    .filter((t) => t !== "")
    .map((t, i) => {
      const boldMatch = /^\*\*([^*]+?)\*\*$/.exec(t);
      if (boldMatch) {
        return (
          <strong key={`${keyBase}-b-${i}`} className="apx-strong">
            {boldMatch[1]}
          </strong>
        );
      }
      const linkMatch = /^\[([^\]]+)\]\(([^)]+)\)$/.exec(t);
      if (linkMatch) {
        return (
          <a
            key={`${keyBase}-a-${i}`}
            href={linkMatch[2]}
            className="apx-link"
            target={linkMatch[2].startsWith("mailto:") ? undefined : "_blank"}
            rel="noopener noreferrer"
          >
            {linkMatch[1]}
          </a>
        );
      }
      // strip any stray/unmatched markdown symbols left in plain text
      const cleaned = t.replace(/\*\*/g, "");
      return cleaned;
    });
}

function renderMarkdown(raw) {
  const lines = raw.replace(/\r\n/g, "\n").split("\n");
  const blocks = [];
  let listItems = [];
  let listType = null;
  let key = 0;

  const flushList = () => {
    if (listItems.length) {
      if (listType === "ol") {
        blocks.push(
          <ol className="apx-ol" key={`list-${key++}`}>
            {listItems}
          </ol>
        );
      } else {
        blocks.push(
          <ul className="apx-ul" key={`list-${key++}`}>
            {listItems}
          </ul>
        );
      }
      listItems = [];
      listType = null;
    }
  };

  lines.forEach((line) => {
    const trimmed = line.trim();

    if (trimmed === "") {
      flushList();
      return;
    }
    if (/^-{3,}$/.test(trimmed)) {
      flushList();
      blocks.push(<hr className="apx-hr" key={`hr-${key++}`} />);
      return;
    }
    if (trimmed.startsWith("### ")) {
      flushList();
      blocks.push(
        <h4 className="apx-h4" key={`h4-${key++}`}>
          {parseInline(trimmed.slice(4), `h4-${key}`)}
        </h4>
      );
      return;
    }
    if (trimmed.startsWith("## ")) {
      flushList();
      blocks.push(
        <h3 className="apx-h3" key={`h3-${key++}`}>
          {parseInline(trimmed.slice(3), `h3-${key}`)}
        </h3>
      );
      return;
    }
    if (trimmed.startsWith("# ")) {
      flushList();
      blocks.push(
        <h2 className="apx-h2" key={`h2-${key++}`}>
          {parseInline(trimmed.slice(2), `h2-${key}`)}
        </h2>
      );
      return;
    }
    if (trimmed.startsWith("> ")) {
      flushList();
      blocks.push(
        <blockquote className="apx-quote" key={`q-${key++}`}>
          {parseInline(trimmed.slice(2), `q-${key}`)}
        </blockquote>
      );
      return;
    }
    if (trimmed.startsWith("* ")) {
      if (listType !== "ul") flushList();
      listType = "ul";
      listItems.push(
        <li key={`li-${key++}`}>{parseInline(trimmed.slice(2), `li-${key}`)}</li>
      );
      return;
    }
    const numMatch = /^(\d+)\.\s+(.*)$/.exec(trimmed);
    if (numMatch) {
      if (listType !== "ol") flushList();
      listType = "ol";
      listItems.push(
        <li key={`li-${key++}`}>{parseInline(numMatch[2], `li-${key}`)}</li>
      );
      return;
    }

    flushList();
    blocks.push(
      <p className="apx-p" key={`p-${key++}`}>
        {parseInline(trimmed, `p-${key}`)}
      </p>
    );
  });

  flushList();
  return blocks;
}

